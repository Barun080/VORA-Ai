# คำค้น → จังหวัด เรียงจากยาวไปสั้น (กัน "นครพนม" ถูกจับเป็น "นคร…" ที่สั้นกว่า และ "สุพรรณบุรี" ก่อน "สุพรรณ")
_INDEX: list[tuple[str, tuple]] = sorted(
    [(normalize(n), p) for p in PROVINCES for n in (p[0], *p[4])] + [(p[1].lower(), p) for p in PROVINCES],
    key=lambda x: -len(x[0]))


# ชื่อที่เป็นคำทั่วไปด้วย ("อากาศดีเลย", "ตากผ้า", "แพร่กระจาย") → นับเป็นจังหวัดเฉพาะเมื่อมีคำนำหน้าบอกสถานที่ หรือพิมพ์มาแค่ชื่อ
_AMBIGUOUS = {"เลย", "ตาก", "แพร่", "ตรัง", "น่าน", "ยะลา", "สตูล", "ระนอง", "พังงา", "อุดร", "อุบล"}
_PLACE_CUE = re.compile(r"(?:จังหวัด|จ\.|ที่|แถว|ใน|อากาศ|ไป)\s*$")


def _ok(key: str, t: str) -> bool:
    if key not in _AMBIGUOUS:
        return True
    i = t.find(key)
    while i >= 0:
        if t.strip() == key or _PLACE_CUE.search(t[:i]):
            return True
        i = t.find(key, i + 1)
    return False


def find(text: str) -> dict | None:
    """หาชื่อจังหวัดในข้อความ → {th, en, lat, lon} หรือ None"""
    t = normalize(text or "")
    tl = (text or "").lower()
    for key, p in _INDEX:
        if not key:
            continue
        if key.isascii():
            hit = re.search(rf"\b{re.escape(key)}\b", tl) is not None
        else:
            hit = key in t and _ok(key, t)
        if hit:
            return {"th": p[0], "en": p[1], "lat": p[2], "lon": p[3]}
    return None
